import { describe, expect, it } from 'vitest'
import ts from 'typescript'
import {
  generateTypes,
  resolveCollectionInterfaceName,
  resolveGlobalInterfaceName,
  singularize,
  toPascalCase,
} from './generator'
import type { Config, CollectionConfig, GlobalConfig } from '@lontar/core'

describe('singularize', () => {
  it('handles regular plural nouns', () => {
    expect(singularize('posts')).toBe('post')
    expect(singularize('authors')).toBe('author')
    expect(singularize('tags')).toBe('tag')
  })

  it('handles -ies plural endings', () => {
    expect(singularize('categories')).toBe('category')
    expect(singularize('stories')).toBe('story')
  })

  it('handles -es plural endings (-xes, -shes, -ches, -sses)', () => {
    expect(singularize('boxes')).toBe('box')
    expect(singularize('dishes')).toBe('dish')
    expect(singularize('watches')).toBe('watch')
    expect(singularize('addresses')).toBe('address')
  })

  it('preserves invariable words and exceptions', () => {
    expect(singularize('media')).toBe('media')
    expect(singularize('news')).toBe('news')
    expect(singularize('series')).toBe('series')
    expect(singularize('species')).toBe('species')
    expect(singularize('status')).toBe('status')
  })
})

describe('toPascalCase', () => {
  it('converts kebab-case, snake_case, and spaced strings to PascalCase', () => {
    expect(toPascalCase('post')).toBe('Post')
    expect(toPascalCase('blog-posts')).toBe('BlogPosts')
    expect(toPascalCase('site_settings')).toBe('SiteSettings')
    expect(toPascalCase('user profile info')).toBe('UserProfileInfo')
    expect(toPascalCase('')).toBe('Document')
  })
})

describe('resolveCollectionInterfaceName & resolveGlobalInterfaceName', () => {
  it('uses labels.singular if defined', () => {
    const col: CollectionConfig = {
      slug: 'articles',
      labels: { singular: 'Blog Post' },
      fields: {},
    }
    expect(resolveCollectionInterfaceName(col)).toBe('BlogPost')
  })

  it('falls back to singularized slug', () => {
    const col: CollectionConfig = {
      slug: 'categories',
      fields: {},
    }
    expect(resolveCollectionInterfaceName(col)).toBe('Category')
  })

  it('uses global label if defined, else slug', () => {
    const g1: GlobalConfig = {
      slug: 'settings',
      label: 'Site Header',
      fields: {},
    }
    const g2: GlobalConfig = {
      slug: 'footer-nav',
      fields: {},
    }
    expect(resolveGlobalInterfaceName(g1)).toBe('SiteHeader')
    expect(resolveGlobalInterfaceName(g2)).toBe('FooterNav')
  })
})

describe('generateTypes', () => {
  it('generates complete, valid TypeScript declarations from config', () => {
    const config: Config = {
      secret: 'test-secret',
      db: { name: 'mock' } as unknown as Config['db'],
      collections: [
        {
          slug: 'authors',
          labels: { singular: 'Author', plural: 'Authors' },
          fields: {
            name: { type: 'text', required: true },
            bio: { type: 'textarea' },
          },
        },
        {
          slug: 'categories',
          fields: {
            name: { type: 'text', required: true },
          },
        },
        {
          slug: 'media',
          upload: {
            sizes: {
              thumb: { width: 400 },
              hero: { width: 1600 },
            },
          },
          fields: {
            alt: { type: 'text', required: true },
          },
        },
        {
          slug: 'posts',
          labels: { singular: 'Post', plural: 'Posts' },
          fields: {
            title: { type: 'text', required: true },
            slug: { type: 'slug' },
            views: { type: 'number' },
            isFeatured: { type: 'checkbox' },
            status: {
              type: 'select',
              options: ['draft', 'published'],
              required: true,
            },
            role: {
              type: 'select',
              options: [
                { label: 'Admin', value: 'admin' },
                { label: 'Editor', value: 'editor' },
              ],
            },
            publishedAt: { type: 'date' },
            content: { type: 'richText' },
            cover: { type: 'upload', relationTo: 'media' },
            author: { type: 'relationship', relationTo: 'authors', required: true },
            categories: {
              type: 'relationship',
              relationTo: 'categories',
              hasMany: true,
            },
          },
        },
      ],
      globals: [
        {
          slug: 'site-settings',
          label: 'Site Settings',
          fields: {
            siteName: { type: 'text', required: true },
            footerText: { type: 'textarea' },
          },
        },
      ],
    }

    const output = generateTypes(config)

    // Checks header
    expect(output).toContain('// Generated by @lontar/cli. Do not edit directly.')

    // Checks Author interface
    expect(output).toContain('export interface Author {')
    expect(output).toContain('  id: number')
    expect(output).toContain('  createdAt: string')
    expect(output).toContain('  updatedAt: string')
    expect(output).toContain('  name: string')
    expect(output).toContain('  bio?: string | null')

    // Checks Category interface
    expect(output).toContain('export interface Category {')

    // Checks Media interface with upload fields and sizes
    expect(output).toContain('export interface Media {')
    expect(output).toContain('  filename: string')
    expect(output).toContain('  url: string')
    expect(output).toContain('  mimeType: string')
    expect(output).toContain('  filesize: number')
    expect(output).toContain('  width?: number | null')
    expect(output).toContain('  height?: number | null')
    expect(output).toContain('  sizes?: {')
    expect(output).toContain('    thumb?: {')
    expect(output).toContain('    hero?: {')

    // Checks Post interface with relationship types and select unions
    expect(output).toContain('export interface Post {')
    expect(output).toContain('  title: string')
    expect(output).toContain('  slug?: string | null')
    expect(output).toContain('  views?: number | null')
    expect(output).toContain('  isFeatured?: boolean | null')
    expect(output).toContain('  status: "draft" | "published"')
    expect(output).toContain('  role?: "admin" | "editor" | null')
    expect(output).toContain('  publishedAt?: string | null')
    expect(output).toContain('  content?: Record<string, unknown> | null')
    expect(output).toContain('  cover?: number | Media | null')
    expect(output).toContain('  author: number | Author')
    expect(output).toContain('  categories?: (number | Category)[] | null')

    // Checks SiteSettings global
    expect(output).toContain('export interface SiteSettings {')
    expect(output).toContain('  siteName: string')
    expect(output).toContain('  footerText?: string | null')

    // Checks Config interface
    expect(output).toContain('export interface Config {')
    expect(output).toContain('    authors: Author')
    expect(output).toContain('    categories: Category')
    expect(output).toContain('    media: Media')
    expect(output).toContain('    posts: Post')
    expect(output).toContain('    "site-settings": SiteSettings')

    // Checks Module augmentation
    expect(output).toContain("declare module '@lontar/core' {")
    expect(output).toContain('  interface LontarCollections {')
    expect(output).toContain('  interface LontarGlobals {')

    // Verify generated code compiles cleanly as valid TypeScript
    const transpileResult = ts.transpileModule(output, {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2022,
      },
    })
    expect(transpileResult.outputText).toBeDefined()
  })

  it('handles collision between interface names gracefully', () => {
    const config: Config = {
      secret: 'test-secret',
      db: { name: 'mock' } as unknown as Config['db'],
      collections: [
        {
          slug: 'config',
          fields: { name: { type: 'text' } },
        },
        {
          slug: 'posts',
          labels: { singular: 'Post' },
          fields: {},
        },
        {
          slug: 'posts-archive',
          labels: { singular: 'Post' },
          fields: {},
        },
      ],
      globals: [
        {
          slug: 'posts',
          label: 'Post',
          fields: {},
        },
      ],
    }

    const output = generateTypes(config)
    expect(output).toContain('export interface ConfigDoc {')
    expect(output).toContain('export interface Post {')
    expect(output).toContain('export interface PostDoc {')
    expect(output).toContain('export interface PostGlobal {')
  })

  it('generates nested types for group fields and nested group fields', () => {
    const config: Config = {
      secret: 'test-secret',
      db: { name: 'mock' } as unknown as Config['db'],
      collections: [
        {
          slug: 'pages',
          fields: {
            title: { type: 'text', required: true },
            seo: {
              type: 'group',
              required: true,
              fields: {
                metaTitle: { type: 'text', required: true },
                metaDescription: { type: 'textarea' },
                og: {
                  type: 'group',
                  fields: {
                    imageAlt: { type: 'text' },
                  },
                },
              },
            },
          },
        },
      ],
    }

    const output = generateTypes(config)
    expect(output).toContain('export interface Page {')
    expect(output).toContain('  title: string')
    expect(output).toContain('  seo: {')
    expect(output).toContain('    metaTitle: string')
    expect(output).toContain('    metaDescription?: string | null')
    expect(output).toContain('    og?: {')
    expect(output).toContain('      imageAlt?: string | null')
    expect(output).toContain('    } | null')
    expect(output).toContain('  }')

    const transpileResult = ts.transpileModule(output, {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2022,
      },
    })
    expect(transpileResult.outputText).toBeDefined()
  })

  it('generates array types with id and row subfields', () => {
    const config: Config = {
      secret: 'test-secret',
      db: { name: 'mock' } as unknown as Config['db'],
      collections: [
        {
          slug: 'portfolio',
          fields: {
            title: { type: 'text', required: true },
            gallery: {
              type: 'array',
              required: true,
              fields: {
                caption: { type: 'text', required: true },
                year: { type: 'number' },
              },
            },
            features: {
              type: 'array',
              fields: {
                name: { type: 'text', required: true },
              },
            },
          },
        },
      ],
    }

    const output = generateTypes(config)
    expect(output).toContain('export interface Portfolio {')
    expect(output).toContain('  title: string')
    expect(output).toContain('  gallery: Array<{')
    expect(output).toContain('    id: string')
    expect(output).toContain('    caption: string')
    expect(output).toContain('    year?: number | null')
    expect(output).toContain('  features?: Array<{')
    expect(output).toContain('    name: string')
    expect(output).toContain('  }> | null')

    const transpileResult = ts.transpileModule(output, {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2022,
      },
    })
    expect(transpileResult.outputText).toBeDefined()
  })

  it('generates block interfaces and discriminated union for blocks fields', () => {
    const config: Config = {
      secret: 'test-secret',
      db: { name: 'mock' } as unknown as Config['db'],
      collections: [
        {
          slug: 'pages',
          fields: {
            title: { type: 'text', required: true },
            layout: {
              type: 'blocks',
              required: true,
              blocks: [
                {
                  slug: 'hero',
                  labels: { singular: 'Hero', plural: 'Heroes' },
                  fields: {
                    heading: { type: 'text', required: true },
                    subheading: { type: 'text' },
                  },
                },
                {
                  slug: 'cta',
                  labels: { singular: 'Call to Action', plural: 'Calls to Action' },
                  fields: {
                    text: { type: 'text', required: true },
                    buttonUrl: { type: 'text', required: true },
                  },
                },
              ],
            },
          },
        },
      ],
    }

    const output = generateTypes(config)
    expect(output).toContain('export interface PageLayoutHeroBlock {')
    expect(output).toContain('  id: string')
    expect(output).toContain("  blockType: 'hero'")
    expect(output).toContain('  heading: string')
    expect(output).toContain('  subheading?: string | null')

    expect(output).toContain('export interface PageLayoutCtaBlock {')
    expect(output).toContain('  id: string')
    expect(output).toContain("  blockType: 'cta'")
    expect(output).toContain('  text: string')
    expect(output).toContain('  buttonUrl: string')

    expect(output).toContain(
      'export type PageLayoutBlock = PageLayoutHeroBlock | PageLayoutCtaBlock',
    )

    expect(output).toContain('export interface Page {')
    expect(output).toContain('  title: string')
    expect(output).toContain('  layout: Array<PageLayoutBlock>')

    const transpileResult = ts.transpileModule(output, {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2022,
      },
    })
    expect(transpileResult.outputText).toBeDefined()
  })

  it('generates populated vs unpopulated types for relationships and uploads inside group, array, and blocks', () => {
    const config: Config = {
      secret: 'test-secret',
      db: { name: 'mock' } as unknown as Config['db'],
      collections: [
        {
          slug: 'media',
          upload: true,
          fields: {
            alt: { type: 'text' },
          },
        },
        {
          slug: 'authors',
          fields: {
            name: { type: 'text', required: true },
          },
        },
        {
          slug: 'articles',
          fields: {
            title: { type: 'text', required: true },
            meta: {
              type: 'group',
              fields: {
                cover: { type: 'upload', relationTo: 'media', required: true },
                leadAuthor: { type: 'relationship', relationTo: 'authors' },
              },
            },
            references: {
              type: 'array',
              fields: {
                article: { type: 'relationship', relationTo: 'articles', required: true },
                coAuthors: { type: 'relationship', relationTo: 'authors', hasMany: true },
              },
            },
            content: {
              type: 'blocks',
              blocks: [
                {
                  slug: 'imageSpotlight',
                  labels: { singular: 'Image Spotlight', plural: 'Image Spotlights' },
                  fields: {
                    image: { type: 'upload', relationTo: 'media', required: true },
                    photographer: { type: 'relationship', relationTo: 'authors' },
                  },
                },
              ],
            },
          },
        },
      ],
    }

    const output = generateTypes(config)

    // Block interface should have populated vs unpopulated types for upload and relationship
    expect(output).toContain('export interface ArticleContentImageSpotlightBlock {')
    expect(output).toContain('  id: string')
    expect(output).toContain("  blockType: 'imageSpotlight'")
    expect(output).toContain('  image: number | Media')
    expect(output).toContain('  photographer?: number | Author | null')

    // Article interface should have group and array with proper reference types
    expect(output).toContain('  meta?: {')
    expect(output).toContain('    cover: number | Media')
    expect(output).toContain('    leadAuthor?: number | Author | null')

    expect(output).toContain('  references?: Array<{')
    expect(output).toContain('    id: string')
    expect(output).toContain('    article: number | Article')
    expect(output).toContain('    coAuthors?: (number | Author)[] | null')

    const transpileResult = ts.transpileModule(output, {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2022,
      },
    })
    expect(transpileResult.outputText).toBeDefined()
  })

  it('marks conditional fields as optional and nullable even when required: true', () => {
    const config: Config = {
      secret: 'test-secret',
      db: { name: 'mock' } as unknown as Config['db'],
      collections: [
        {
          slug: 'posts',
          fields: {
            title: { type: 'text', required: true },
            format: {
              type: 'select',
              options: ['standard', 'video'],
              defaultValue: 'standard',
            },
            videoUrl: {
              type: 'text',
              required: true,
              admin: { condition: { format: { equals: 'video' } } },
            },
            settings: {
              type: 'group',
              admin: { condition: { format: { equals: 'video' } } },
              fields: {
                duration: { type: 'number', required: true },
              },
            },
          },
        },
      ],
    }

    const output = generateTypes(config)
    expect(output).toContain('  title: string')
    expect(output).toContain('  videoUrl?: string | null')
    expect(output).not.toContain('  videoUrl: string')
    expect(output).toContain('  settings?: {')
    expect(output).toContain('    duration?: number | null')
    expect(output).not.toContain('    duration: number')

    const transpileResult = ts.transpileModule(output, {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2022,
      },
    })
    expect(transpileResult.outputText).toBeDefined()
  })

  it('includes _status: "draft" | "published" when drafts are enabled', () => {
    const config: Config = {
      secret: 'test-secret',
      db: { name: 'mock' } as unknown as Config['db'],
      collections: [
        {
          slug: 'posts',
          versions: { drafts: true },
          fields: {
            title: { type: 'text', required: true },
          },
        },
      ],
      globals: [
        {
          slug: 'settings',
          versions: { drafts: true },
          fields: {
            siteName: { type: 'text', required: true },
          },
        },
      ],
    }

    const output = generateTypes(config)
    expect(output).toContain("  _status: 'draft' | 'published'")

    const transpileResult = ts.transpileModule(output, {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2022,
      },
    })
    expect(transpileResult.outputText).toBeDefined()
  })
})
